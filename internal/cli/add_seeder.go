package cli

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/spf13/cobra"

	"github.com/gp-system/framework/internal/generator"
	"github.com/gp-system/framework/internal/templates"
)

func addSeederCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "seeder <name>",
		Short: "Add a database seeder (idempotent baseline data, run via cmd/migrate --seed)",
		Long: `Creates a seeder stub in the project's central seeds/ package and registers it.
The seeder returns a seed.Seeder: a Name, an optional Guard deciding whether it
runs at all, and the Run body. Run "go run ./cmd/migrate up --seed" (or
"... seed" to seed without migrating) to execute every registered seeder.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			name := args[0]
			if generator.ToPascal(name) == "" {
				return fmt.Errorf("seeder name %q is empty after normalization", name)
			}

			proj, err := generator.OpenProject(".")
			if err != nil {
				return err
			}
			warnProject(cmd, proj)

			registerGo := filepath.Join(proj.Root, "seeds", "register.go")
			if _, err := os.Stat(registerGo); err != nil {
				return fmt.Errorf("this project has no seeds/register.go (expected in projects generated by a recent `new project`): %w", err)
			}

			seedName := generator.ToCamel(name)
			for _, s := range proj.Manifest.Seeds {
				if s == seedName {
					return fmt.Errorf("a seeder named %q already exists", seedName)
				}
			}

			data := generator.Data{
				Project:  projName(proj),
				GoModule: proj.Manifest.Module,
				Seed:     seedName,
				DB:       proj.Manifest.DBName(),
				Kit:      kitRef(""),
				Errs:     errsRef(""),
			}

			eng := newEngine(cmd)
			files, err := eng.RenderTree(templates.FS, "seedfile", data, proj.Root)
			if err != nil {
				return err
			}
			if err := eng.Apply(files); err != nil {
				return err
			}
			if err := insertSnippet(eng, registerGo, "gpsystem:seeds", "seed-register", data); err != nil {
				return err
			}
			if err := eng.FormatGoFile(registerGo); err != nil {
				return err
			}

			if !dryRunFlag(cmd) {
				if err := proj.Manifest.AddSeed(data.Seed); err != nil {
					return err
				}
				if err := proj.Manifest.Save(proj.Root); err != nil {
					return err
				}
			}

			fmt.Fprintf(cmd.OutOrStdout(), `
Seeder %q added. Implement it in seeds/%s.go, then run:

  go run ./cmd/migrate up --seed   # migrate, then seed
  go run ./cmd/migrate seed        # seed only
`, data.Seed, generator.ToSnake(data.Seed))
			return nil
		},
	}
}
