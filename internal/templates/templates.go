// Package templates holds the embedded template assets of the gpsystem CLI.
//
// Trees:
//   - project/  : consumer project skeleton (rendered)
//   - module/   : module skeleton: cmd entry point + surfaces/register.go
//     (rendered)
//   - surface/  : one surface (parallel HTTP bundle): http/service/policy +
//     tsp + codegen config (rendered); the module-root domain files and the
//     repository/ skeleton come from moduledomain/
//   - moduledomain/ : a module's root domain files (entities, rules,
//     sentinels; package named after the module) and module-level
//     repository/ skeleton (rendered); stamped by the first `add surface` on
//     a module (skipped when the module root already has .go files) and by
//     `add domain` as a retrofit
//   - worker/   : the project's cmd/worker entry point (rendered); added by
//     `new project` and `add worker`
//   - moduleworker/ : a module's listeners/register.go + jobs/register.go
//     stubs (rendered)
//   - event/    : one event struct (rendered)
//   - listener/ : one event listener stub (rendered)
//   - job/      : one scheduled job stub (rendered)
//   - mail/     : one mail notifier: payload + Notifier (rendered) plus its
//     html/text templates (copied verbatim: they are html/template sources
//     consumed at runtime by mail.Template, not gpsystem scaffolding inputs)
//   - notification/ : one Laravel-style notification: payload + Via +
//     per-channel content (rendered) plus its html/text templates (copied
//     verbatim, same reasoning as mail/) and its database-channel migration
//     (read directly by the CLI, not part of the rendered tree)
//   - realtime/ : the project's cmd/realtime entry point (rendered); added
//     by `add realtime`
//   - seedfile/: one seeder stub added to the project's central seeds/
//     package (rendered); added by `add seeder`. The seeds/ package itself
//     (Deps + Register with its gpsystem:seeds anchor) is part of project/,
//     generated by `new project` like migrations/.
//   - auth/    : a full auth module (rendered): the api surface's TypeSpec +
//     http/service layers plus the module-root domain files and repository/,
//     implementing register (with email
//     verification), login, refresh, logout and forgot/reset password over a
//     DB-backed RBAC schema (users/roles/permissions/role_permissions/
//     user_roles), plus its two mail notifiers and their html/text templates
//     (copied verbatim, same reasoning as mail/) and one goose migration per
//     table (read directly by the CLI, not part of the rendered tree); added
//     by `add auth`
//   - snippets/ : fragments inserted at gpsystem:* anchor comments (rendered)
//   - oapi/     : oapi-codegen template overrides for chi: a minimal override
//     set (the two strict templates, renamed types only), copied into
//     consumer projects VERBATIM: they contain {{...}} actions themselves
//     and must never be rendered by the engine; routing templates come from
//     oapi-codegen's built-in chi set.
package templates

import (
	"embed"
	"fmt"
	"io/fs"
)

// FS is the embedded template asset tree; see the package doc for its layout.
//
//go:embed all:oapi all:project all:module all:surface all:moduledomain all:handler all:snippets
//go:embed all:worker all:moduleworker all:event all:listener all:job all:mail all:notification all:realtime
//go:embed all:auth all:authassets all:authmigration all:seedfile
var FS embed.FS

// OAPI returns the chi oapi-codegen template overrides.
func OAPI() (fs.FS, error) {
	return fs.Sub(FS, "oapi")
}

// Snippet returns the raw text of a snippet template by base name
// (e.g. "register-surface").
func Snippet(name string) (string, error) {
	data, err := FS.ReadFile("snippets/" + name + ".tmpl")
	if err != nil {
		return "", fmt.Errorf("snippet %q: %w", name, err)
	}
	return string(data), nil
}
